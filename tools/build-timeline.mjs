// One-off/re-runnable helper for the landing-page timeline:
//  1. writes assets/css/timeline-masks.css (torn-paper + pixel-dissolve edge masks as data URIs)
//  2. wraps each .era in index.html with a scene header, textured body and seams (idempotent)
// Usage: node tools/build-timeline.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const uri = (svg) => `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/%20/g, " ").replace(/%2C/g, ",").replace(/%2F/g, "/").replace(/%3A/g, ":").replace(/%3D/g, "=")}")`;

function torn(seed, W = 1600, H = 72) {
  const r = rng(seed);
  const p1 = r() * 6.28, p2 = r() * 6.28, p3 = r() * 6.28;
  const y = (x) => 30 + 13 * Math.sin((x / W) * 6.2832 * 3 + p1) + 7 * Math.sin((x / W) * 6.2832 * 8 + p2) + 3 * Math.sin((x / W) * 6.2832 * 21 + p3);
  const y0 = y(0);
  let d = `M0,${y0.toFixed(1)}`;
  for (let x = 4 + r() * 6; x < W - 6; x += 3 + r() * 8) d += `L${x.toFixed(1)},${(y(x) + (r() - 0.5) * 9).toFixed(1)}`;
  d += `L${W},${y0.toFixed(1)}V${H}H0Z`;
  return uri(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="none"><path d="${d}"/></svg>`);
}
function pixels(seed, cols = 48, rows = 6, s = 12) {
  const r = rng(seed);
  let d = "";
  for (let j = 0; j < rows; j++) for (let i = 0; i < cols; i++) if (r() < (j + 0.5) / (rows + 0.4)) d += `M${i * s},${j * s}h${s}v${s}h-${s}z`;
  return uri(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${cols * s} ${rows * s}" shape-rendering="crispEdges"><path d="${d}"/></svg>`);
}
fs.writeFileSync(path.join(ROOT, "assets/css/timeline-masks.css"),
  `/* generated by tools/build-timeline.mjs */\n:root {\n  --m-torn-a: ${torn(1898)};\n  --m-torn-b: ${torn(1941)};\n  --m-pixel: ${pixels(2019)};\n}\n`);

// ---------- wrap eras ----------
