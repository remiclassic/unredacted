  1963: { line: "Dallas · 22 November 1963", alt: "Illustration in the style of 1963 home-movie film: crowds line a sunny downtown street as a motorcade approaches",
    top: `<div class="strip film top" aria-hidden="true"><span>${"Safety film ▸ 22 Nov 63 ▸ 12 ▸ 12A ▸ 13 ▸ 13A ▸ ".repeat(8)}</span></div>`,
    bot: `<div class="strip film bot" aria-hidden="true"><span>${"Safety film ▸ 22 Nov 63 ▸ 14 ▸ 14A ▸ 15 ▸ 15A ▸ ".repeat(8)}</span></div>` },
